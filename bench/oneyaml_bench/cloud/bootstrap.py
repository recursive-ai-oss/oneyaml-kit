"""The scripts an instance runs at boot (passed as user data).

A shard script downloads the inputs, runs the benchmark commands, uploads the results and powers
off. It always powers off: on success, on any error, and, through a lifetime limit set before
anything else, even if it hangs. The instance has no credentials; every transfer goes through a
presigned URL placed in the script.
"""

from __future__ import annotations

import gzip
import shlex
from dataclasses import dataclass, field

from . import toolchains

WORK = "/work"
CACHE = "/opt/kit-cache"
LOG_FILE = "/var/log/kit-run.log"
# The line the driver prints when it starts measuring; the script notes the time it first appears.
MEASURING_PATTERN = "measuring ("


@dataclass
class ShardScript:
    run_id: str
    shard: str                       # a label, e.g. "1/2"
    attempt: int
    commands: list[list[str]]        # bin/bench arguments; "{out}" becomes the output directory of that command
    inputs_url: str
    log_url: str
    status_url: str
    result_url: str
    lifetime_minutes: int
    library_vars: dict[str, str] = field(default_factory=dict)   # env var -> pack name present in the inputs


def _q(s: str) -> str:
    return shlex.quote(s)


# Shell shared by both scripts. Everything the script needs to find its way out is defined before
# any step that can fail or hang.
PRELUDE = r"""#!/bin/bash
# Generated by the benchmark launcher. Holds URLs for single objects and plain settings only.
set -u
shutdown -h +__LIFETIME__ "lifetime limit reached" || true
LOG=__LOG__
: > "$LOG"; rm -f /var/log/kit-marks
mkdir -p __WORK__ && cd __WORK__ || exit 1
exec >>"$LOG" 2>&1
now() { date +%s.%N; }
MARKS=/var/log/kit-marks
mark() { echo "$1 $(now)" >> "$MARKS"; }
up=$(cut -d' ' -f1 /proc/uptime)
echo "boot $(python3 -c "import time; print(time.time() - $up)")" >> "$MARKS"
mark script_start
put() { curl -sS --max-time 120 -X PUT -H 'Expect:' --upload-file "$1" "$2" >/dev/null || true; }
( while sleep 3; do put "$LOG" __LOG_URL__; done ) &
STREAM=$!
echo "== run __RUN__ shard __SHARD__ attempt __ATTEMPT__"
"""


def _fill(text: str, values: dict[str, str]) -> str:
    for k, v in values.items():
        text = text.replace(f"__{k}__", v)
    return text


def shard_script(s: ShardScript) -> str:
    pre = _fill(PRELUDE, {"LIFETIME": str(int(s.lifetime_minutes)), "LOG": LOG_FILE, "WORK": WORK, "LOG_URL": _q(s.log_url),
                          "RUN": s.run_id, "SHARD": s.shard, "ATTEMPT": str(s.attempt)})
    runs = []
    for k, args in enumerate(s.commands):
        words = " ".join(_q(a).replace("'{out}'", '"$OUT/' + str(k) + '"').replace("{out}", '"$OUT/' + str(k) + '"')
                         for a in args)
        runs.append(f'mkdir -p "$OUT/{k}"\necho {_q(f"== bench {k}: " + " ".join(args))}\n'
                    f"python3 bin/bench {words}\nrc=$?\n"
                    f'if [ $rc -ne 0 ]; then echo "bench command {k} exited with status $rc"; exit $rc; fi')
    libs = "\n".join(
        f'export {var}={WORK}/src/{name}' for var, name in sorted(s.library_vars.items()))
    body = r"""
trap 'finish' EXIT
OUT=__WORK__/out
finish() {
  rc=${RC:-$?}
  kill $STREAM 2>/dev/null
  mark finished
  python3 - "$rc" <<'PY'
import json, sys, os
marks = {}
for line in open("/var/log/kit-marks"):
    k, v = line.split()
    marks.setdefault(k, float(v))
info = {k: os.environ.get(k, "") for k in ("KIT_INSTANCE_TYPE", "KIT_INSTANCE_AZ", "KIT_INSTANCE_LIFECYCLE")}
json.dump({"done": True, "exit": int(sys.argv[1]), "marks": marks, "instance": info,
           "governor": os.environ.get("KIT_GOVERNOR", "")}, open("/var/log/kit-status.json", "w"))
PY
  # Results are sent even when the run failed, so the failure can be read.
  [ -d "$OUT" ] && tar -C "$OUT" --exclude=workloads --exclude=target -czf __WORK__/result.tar.gz . 2>/dev/null
  if [ -s __WORK__/result.tar.gz ]; then put __WORK__/result.tar.gz __RESULT_URL__; fi
  put "$LOG" __LOG_URL__
  put /var/log/kit-status.json __STATUS_URL__
  sleep 1
  shutdown -h now
}

# The stock services that wake up on their own would add noise to the timings.
systemctl stop apt-daily.timer apt-daily-upgrade.timer unattended-upgrades snapd 'amazon-ssm*' 2>/dev/null
# Read the cached toolchains and dependencies into memory while the inputs download: a volume made from
# an image loads blocks on first read.
( find __CACHE__ /opt/go /opt/dotnet /opt/rust -type f -print0 2>/dev/null | xargs -0 -P 16 -n 64 cat >/dev/null 2>&1 ) &
WARM=$!

TOKEN=$(curl -sS -X PUT http://169.254.169.254/latest/api/token -H 'X-aws-ec2-metadata-token-ttl-seconds: 600')
md() { curl -sS -H "X-aws-ec2-metadata-token: $TOKEN" "http://169.254.169.254/latest/meta-data/$1"; }
# The harness records the instance type in its environment block from this variable.
export KIT_INSTANCE_TYPE=$(md instance-type) KIT_INSTANCE_AZ=$(md placement/availability-zone)
export KIT_INSTANCE_LIFECYCLE=$(md instance-life-cycle)
echo "instance $KIT_INSTANCE_TYPE $KIT_INSTANCE_AZ $KIT_INSTANCE_LIFECYCLE"

# Governor and idle states: only where the platform lets the guest do it.
for g in /sys/devices/system/cpu/cpu*/cpufreq/scaling_governor; do [ -w "$g" ] && echo performance > "$g"; done
python3 -c 'import os, time; fd = os.open("/dev/cpu_dma_latency", os.O_WRONLY); os.write(fd, bytes(4)); time.sleep(10**7)' &
export KIT_GOVERNOR=$(cat /sys/devices/system/cpu/cpu0/cpufreq/scaling_governor 2>/dev/null || echo unknown)
echo "governor $KIT_GOVERNOR; kernel $(uname -r); cpus $(nproc)"
mark setup_done

curl -sSfL --retry 3 -o __WORK__/inputs.tar __INPUTS_URL__ || { echo "inputs download failed"; exit 11; }
tar -xf __WORK__/inputs.tar -C __WORK__ || exit 12
mkdir -p __WORK__/kit __WORK__/src
tar -xzf __WORK__/kit.tar.gz -C __WORK__/kit || exit 13
for f in __WORK__/lib-*.tar.gz; do
  [ -e "$f" ] || continue
  n=$(basename "$f" .tar.gz); n=${n#lib-}
  mkdir -p __WORK__/src/$n && tar -xzf "$f" -C __WORK__/src/$n || exit 14
  # The archive carries no history; a stub repository lets the build scripts read the revision.
  rev=$(cat __WORK__/rev-$n)
  git -C __WORK__/src/$n init -q . && echo "$rev" > __WORK__/src/$n/.git/refs/heads/main \
    && git -C __WORK__/src/$n symbolic-ref HEAD refs/heads/main
done
mark inputs_ready
wait $WARM
mark cache_warm

export PATH=/opt/go/bin:/opt/dotnet:/opt/rust/cargo/bin:$PATH HOME=/root
export GOCACHE=__CACHE__/go-build GOMODCACHE=__CACHE__/gomod GOFLAGS=-buildvcs=false GOTOOLCHAIN=local
export NUGET_PACKAGES=__CACHE__/nuget DOTNET=/opt/dotnet/dotnet DOTNET_CLI_TELEMETRY_OPTOUT=1 DOTNET_NOLOGO=1
export DOTNET_ROOT=/opt/dotnet CARGO_HOME=/opt/rust/cargo RUSTUP_HOME=/opt/rust/rustup CARGO_TERM_COLOR=never
# Unbuffered, so the streamed log shows each line as it is printed and the measuring mark is timely.
export PYTHONUNBUFFERED=1
export CARGO_TARGET_DIR=__CACHE__/build KIT_OUT=$OUT
__LIBS__
mkdir -p "$OUT"
cd __WORK__/kit
( until grep -q -F '__MEASURING__' "$LOG" 2>/dev/null; do sleep 0.3; done; mark measuring ) &
mark bench_start
__RUNS__
mark bench_done
# Provenance the harness cannot read from an archive: the kit revision, and the instance type when the
# harness did not record it itself.
python3 - <<'PY'
import glob, json, os
rev = open("__WORK__/rev-kit").read().strip()
for path in glob.glob(os.environ["KIT_OUT"] + "/*/results.json"):
    r = json.load(open(path))
    env = r.get("run", {}).get("environment")
    if env is None:
        continue
    env.setdefault("instance_type", os.environ.get("KIT_INSTANCE_TYPE", ""))
    if not env.get("instance_type"):
        env["instance_type"] = os.environ.get("KIT_INSTANCE_TYPE", "")
    if not env.get("kit_revision"):
        env["kit_revision"] = rev[:12]
    json.dump(r, open(path, "w"), indent=1)
PY
RC=0
"""
    body = _fill(body, {"WORK": WORK, "CACHE": CACHE, "RESULT_URL": _q(s.result_url), "LOG_URL": _q(s.log_url),
                        "STATUS_URL": _q(s.status_url), "INPUTS_URL": _q(s.inputs_url), "LIBS": libs,
                        "RUNS": "\n".join(runs), "MEASURING": MEASURING_PATTERN})
    return pre + body


def bake_script(kit_url: str, log_url: str, status_url: str, lifetime_minutes: int, run_id: str) -> str:
    """The image bake: installs every toolchain, then warms the dependency and build caches."""
    pre = _fill(PRELUDE, {"LIFETIME": str(int(lifetime_minutes)), "LOG": LOG_FILE, "WORK": WORK, "LOG_URL": _q(log_url),
                          "RUN": run_id, "SHARD": "image", "ATTEMPT": "1"})
    body = r"""
OUT=__WORK__/out
finish() {
  rc=${RC:-$?}
  kill $STREAM 2>/dev/null
  echo "{\"done\": true, \"exit\": $rc}" > /var/log/kit-status.json
  put "$LOG" __LOG_URL__
  put /var/log/kit-status.json __STATUS_URL__
  sleep 1
  # The bake instance stops rather than terminates, so the launcher can image its volume.
  shutdown -h now
}
trap 'finish' EXIT
export DEBIAN_FRONTEND=noninteractive
mark bake_start
apt-get update -qq && apt-get install -y -qq --no-install-recommends __APT__ || exit 20
mkdir -p /opt/go /opt/dotnet /opt/rust __CACHE__
curl -sSfL --retry 3 -o /work/inputs.tar __KIT_URL__ || exit 21
tar -xf /work/inputs.tar -C /work && mkdir -p /work/kit && tar -xzf /work/kit.tar.gz -C /work/kit || exit 22
( curl -sSfL --retry 3 __GO_URL__ | tar -xz -C /opt ) || exit 23
( curl -sSfL --retry 3 -o /tmp/dotnet.tgz __DOTNET_URL__ && tar -xzf /tmp/dotnet.tgz -C /opt/dotnet && rm /tmp/dotnet.tgz ) || exit 24
export RUSTUP_HOME=/opt/rust/rustup CARGO_HOME=/opt/rust/cargo
curl -sSfL --retry 3 -o /tmp/rustup-init __RUSTUP_URL__ && chmod +x /tmp/rustup-init \
  && /tmp/rustup-init -y --no-modify-path --profile minimal --default-toolchain __RUST_VERSION__ || exit 25
mark toolchains_done
export PATH=/opt/go/bin:/opt/dotnet:/opt/rust/cargo/bin:$PATH HOME=/root
export GOCACHE=__CACHE__/go-build GOMODCACHE=__CACHE__/gomod GOFLAGS=-buildvcs=false GOTOOLCHAIN=local
export NUGET_PACKAGES=__CACHE__/nuget DOTNET=/opt/dotnet/dotnet DOTNET_CLI_TELEMETRY_OPTOUT=1 DOTNET_NOLOGO=1
export DOTNET_ROOT=/opt/dotnet CARGO_TERM_COLOR=never
B=__CACHE__/build
mkdir -p "$B"
# Build each harness once, at the path a run uses, so a run only recompiles what changed.
( cd /work/kit/bench/go && sh build.sh "$B" ) || exit 30
( cd /work/kit/bench/rust && CARGO_TARGET_DIR="$B" cargo build --release --locked --quiet ) || exit 31
( cd /work/kit/bench/csharp && ./build.sh "$B" ) || exit 32
go version; "$DOTNET" --version; rustc --version
rm -rf /work/* /tmp/* /var/lib/apt/lists/* /var/log/kit-marks
mark bake_done
RC=0
"""
    t = toolchains.PINS
    body = _fill(body, {"WORK": WORK, "CACHE": CACHE, "LOG_URL": _q(log_url), "STATUS_URL": _q(status_url),
                        "KIT_URL": _q(kit_url), "APT": " ".join(t["apt"]), "GO_URL": _q(toolchains.go_url()),
                        "DOTNET_URL": _q(toolchains.dotnet_url()), "RUSTUP_URL": _q(toolchains.RUSTUP_URL),
                        "RUST_VERSION": t["rust"]})
    return pre + body


def pack_user_data(script: str) -> bytes:
    """Compressed, so the presigned URLs fit the user data limit; the boot process unpacks it."""
    return gzip.compress(script.encode("utf-8"), 9, mtime=0)
